// Builds src/player.js: vendors soundtouchjs (dist/soundtouch.js minus export) + build/player.core.js in one IIFE.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
let st = fs.readFileSync(path.join(root, 'node_modules/soundtouchjs/dist/soundtouch.js'), 'utf8');
st = st.replace(/^export \{[^}]*\};?\s*$/m, '').replace(/^\/\/# sourceMappingURL.*$/m, '');
const core = fs.readFileSync(path.join(__dirname, 'player.core.js'), 'utf8');
const out = `/* StemPlayer - generated by build/build-player.js. Includes SoundTouchJS (LGPL-2.1+, Olli Parviainen / Ryan Berdeen / Jakub Fiala). Classic script: defines window.StemPlayer */
(function (root) {
'use strict';
${st}
${core}
root.StemPlayer = StemPlayer;
})(typeof self !== 'undefined' ? self : typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(root, 'src/player.js'), out);
console.log('player.js', out.length, 'bytes');
